    <h2>1. Taarifa za mtoto</h2>
    <ul>
        <li>Andika jina kamili la mtoto kama linavyoonekana kwenye nyaraka zake rasmi.</li>
        <li>Jaza tarehe ya kuzaliwa, umri, jinsia, shule, darasa na eneo kwenye sehemu husika.</li>
        <li>Chagua mambo anayopenda mtoto na eleza vipaji pamoja na malengo yake kwa usahihi kadiri iwezekanavyo.</li>
    </ul>

    <h2>2. Taarifa za mzazi au mlezi</h2>
    <ul>
        <li>Andika jina kamili la mzazi au mlezi, uhusiano wake na mtoto, na namba ya simu inayopatikana.</li>
        <li>Anwani ya barua pepe na taarifa za mtu wa kuwasiliana naye wakati wa dharura zinaweza kujazwa pale sehemu hizo zinapopatikana.</li>
        <li>Kagua taarifa za mtoto na uandike maelezo yoyote ya ziada kuhusu ridhaa kwenye sehemu iliyotolewa.</li>
    </ul>

    <h2>3. Kagua na tuma fomu</h2>
    <ul>
        <li>Jaza sehemu zote zilizoonyeshwa kuwa za lazima na hakikisha taarifa ni sahihi.</li>
        <li>Mzazi au mlezi lazima asome na akubali tamko la makubaliano kwenye fomu kabla ya kuituma.</li>
        <li>Bonyeza <strong>Wasilisha Usajili</strong> mara moja. Subiri uthibitisho unaoonekana kwenye skrini kabla ya kuondoka kwenye ukurasa.</li>
    </ul>

